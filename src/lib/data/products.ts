/* ------------------- Demoledores de concreto (c6) ------------------- */
// Todas las marcas manejan 22, 25 y 30 kg; se arman con la misma ficha base.

const DEMOLEDOR_SIZES = {
  22: { watts: 1500, joules: 45, bpm: "1,300", price: 18900 },
  25: { watts: 1750, joules: 52, bpm: "1,250", price: 23900 },
  30: { watts: 2000, joules: 62, bpm: "1,100", price: 29900 },
} as const;

/** Factor de precio por marca sobre el precio base del tamaño. */
const DEMOLEDOR_BRANDS = {
  Hilti: { code: "HI", factor: 1.45, rating: 4.9 },
  Bosch: { code: "BO", factor: 1, rating: 4.8 },
  Makita: { code: "MK", factor: 1.05, rating: 4.8 },
  DeWalt: { code: "DW", factor: 0.98, rating: 4.7 },
} as const;

function demoledor(
  brand: keyof typeof DEMOLEDOR_BRANDS,
  kg: keyof typeof DEMOLEDOR_SIZES,
  id: string,
  extra: Partial<Product> = {},
): Product {
  const size = DEMOLEDOR_SIZES[kg];
  const b = DEMOLEDOR_BRANDS[brand];
  const price = Math.round((size.price * b.factor) / 100) * 100 - 1;
  return {
    id,
    slug: `demoledor-concreto-${brand.toLowerCase()}-${kg}kg`,
    sku: `${b.code}-DEM-${kg}`,
    name: `Demoledor de concreto ${kg} kg ${size.watts.toLocaleString("en-US")}W`,
    brand,
    highlight: `${kg} KG`,
    categoryId: "c6",
    price,
    rating: b.rating,
    reviewCount: 40 + kg * 3,
    stock: 3 + (kg % 7),
    description: `Martillo demoledor ${brand} de ${kg} kg para romper losas, banquetas, pisos y cimentaciones de concreto. Sistema antivibración en la empuñadura, motor de uso continuo y zanco hexagonal de 1-1/8" compatible con cinceles y puntas estándar.`,
    includes: [`1 demoledor ${kg} kg`, "1 punta y 1 cincel plano", "Carro o maletín de transporte", "Llave y grasa para zanco"],
    specs: [
      { label: "Peso", value: `${kg} kg` },
      { label: "Potencia", value: `${size.watts.toLocaleString("en-US")} W` },
      { label: "Energía de impacto", value: `${size.joules} J` },
      { label: "Golpes por minuto", value: size.bpm },
      { label: "Zanco", value: 'Hexagonal 1-1/8" (28.6 mm)' },
      { label: "Voltaje", value: "127 V" },
    ],
    images: [],
    createdAt: "2026-06-01",
    ...extra,
  };
}

